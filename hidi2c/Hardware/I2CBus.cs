using System.Text;

namespace HidI2cSimulation.Hardware;

/// <summary>
/// =========================================================================================
///  I2C BUS SIMULATION WITH LOGIC ANALYZER / WIRE TRACER
/// =========================================================================================
///
///  The Inter-Integrated Circuit (I2C) bus uses 2 bi-directional open-drain lines:
///    - SCL (Serial Clock)
///    - SDA (Serial Data)
///
///  A typical HID-over-I2C Read transaction has this exact structure:
///
///  1. Host sends START condition (SDA pulled Low while SCL is High).
///  2. Host sends 7-bit Slave Address + Write bit (0).
///  3. Slave responds with ACK (A = 0).
///  4. Host transmits 16-bit Register Address (Sub-Address) in Little-Endian:
///     - Register Low Byte  (e.g., 0x01) -> Slave ACK
///     - Register High Byte (e.g., 0x00) -> Slave ACK
///  5. Host sends REPEATED START (Sr) without releasing the bus.
///  6. Host sends 7-bit Slave Address + Read bit (1).
///  7. Slave responds with ACK.
///  8. Slave streams Data bytes:
///     - Byte 0: Length LSB -> Host ACK
///     - Byte 1: Length MSB -> Host ACK
///     - Byte 2..N: Payload -> Host ACK (Host NACK on final byte)
///  9. Host sends STOP condition (SDA pulled High while SCL is High).
///
///  ASCII TIMING DIAGRAM:
///
///          +---+ +---+ +---+ +---+ +---+ +---+ +---+ +---+ +---+     +---+ +---+
///  SCL:  __| 1 |_| 2 |_| 3 |_| 4 |_| 5 |_| 6 |_| 7 |_| 8 |_| 9 | ... | 8 |_| 9 |__
///        ---             Slave Address (7-bit) + W     ACK         Data  NACK/P
///  SDA:  \___[ A6 ][ A5 ][ A4 ][ A3 ][ A2 ][ A1 ][ A0 ][ W ][ 0 ] ... [D0][ 1 ]---/
///        ^                                            ^              ^
///      START                                         ACK            STOP
///
/// =========================================================================================
/// </summary>

public interface II2CSlave
{
    byte I2CAddress { get; }
    byte[] HandleRead(ushort registerAddress, int requestedLength);
    bool HandleWrite(ushort registerAddress, byte[] data);
}

public enum I2CEventType
{
    Start,
    RepeatedStart,
    AddressWrite,
    AddressRead,
    RegisterAddress,
    DataRead,
    DataWrite,
    Ack,
    Nack,
    Stop
}

public record I2CTraceRecord(
    DateTime Timestamp,
    I2CEventType EventType,
    string Description,
    byte[]? RawBytes = null
);

public class I2CBus
{
    private readonly Dictionary<byte, II2CSlave> _slaves = new();
    private readonly List<I2CTraceRecord> _traceLog = new();

    public IReadOnlyList<I2CTraceRecord> TraceLog => _traceLog;
    public event Action<I2CTraceRecord>? OnTrace;

    public void RegisterSlave(II2CSlave slave)
    {
        _slaves[slave.I2CAddress] = slave;
    }

    public void ClearTrace()
    {
        _traceLog.Clear();
    }

    private void Log(I2CEventType type, string desc, byte[]? data = null)
    {
        var record = new I2CTraceRecord(DateTime.UtcNow, type, desc, data);
        _traceLog.Add(record);
        OnTrace?.Invoke(record);
    }

    /// <summary>
    /// Performs an I2C Write transaction:
    /// [START] -> [Addr + W] -> [Reg LSB] -> [Reg MSB] -> [Data...] -> [STOP]
    /// </summary>
    public bool Write(byte slaveAddress, ushort registerAddress, byte[] data)
    {
        Log(I2CEventType.Start, "START condition generated by Host");

        byte addrByte = (byte)((slaveAddress << 1) | 0x00);
        Log(I2CEventType.AddressWrite, $"SLA+W (0x{slaveAddress:X2} << 1 | 0 = 0x{addrByte:X2})", new[] { addrByte });

        if (!_slaves.TryGetValue(slaveAddress, out var slave))
        {
            Log(I2CEventType.Nack, $"NACK! No slave responded at address 0x{slaveAddress:X2}");
            Log(I2CEventType.Stop, "STOP condition generated");
            return false;
        }

        Log(I2CEventType.Ack, $"ACK received from Slave 0x{slaveAddress:X2}");

        byte regLsb = (byte)(registerAddress & 0xFF);
        byte regMsb = (byte)((registerAddress >> 8) & 0xFF);
        Log(I2CEventType.RegisterAddress, $"Register Sub-Address: 0x{registerAddress:X4} [LSB: 0x{regLsb:X2}, MSB: 0x{regMsb:X2}]", new[] { regLsb, regMsb });
        Log(I2CEventType.Ack, "ACK for Register Address bytes");

        if (data.Length > 0)
        {
            Log(I2CEventType.DataWrite, $"Writing {data.Length} data bytes: [{string.Join(" ", data.Select(b => $"0x{b:X2}"))}]", data);
            Log(I2CEventType.Ack, $"ACK for Data Payload ({data.Length} bytes)");
        }

        bool result = slave.HandleWrite(registerAddress, data);
        Log(I2CEventType.Stop, "STOP condition generated by Host");
        return result;
    }

    /// <summary>
    /// Performs an I2C Read transaction using Repeated Start:
    /// [START] -> [Addr + W] -> [Reg LSB] -> [Reg MSB] -> [REPEATED START] -> [Addr + R] -> [Read Data...] -> [STOP]
    /// </summary>
    public byte[] Read(byte slaveAddress, ushort registerAddress, int requestedLength)
    {
        Log(I2CEventType.Start, "START condition generated by Host");

        byte addrWriteByte = (byte)((slaveAddress << 1) | 0x00);
        Log(I2CEventType.AddressWrite, $"SLA+W (0x{slaveAddress:X2} << 1 | 0 = 0x{addrWriteByte:X2})", new[] { addrWriteByte });

        if (!_slaves.TryGetValue(slaveAddress, out var slave))
        {
            Log(I2CEventType.Nack, $"NACK! No slave responded at address 0x{slaveAddress:X2}");
            Log(I2CEventType.Stop, "STOP condition generated");
            return Array.Empty<byte>();
        }

        Log(I2CEventType.Ack, $"ACK received from Slave 0x{slaveAddress:X2}");

        byte regLsb = (byte)(registerAddress & 0xFF);
        byte regMsb = (byte)((registerAddress >> 8) & 0xFF);
        Log(I2CEventType.RegisterAddress, $"Register Sub-Address: 0x{registerAddress:X4} [LSB: 0x{regLsb:X2}, MSB: 0x{regMsb:X2}]", new[] { regLsb, regMsb });
        Log(I2CEventType.Ack, "ACK for Register Address bytes");

        // Repeated Start to switch from Write (sub-addressing) to Read mode
        Log(I2CEventType.RepeatedStart, "REPEATED START (Sr) condition generated by Host");

        byte addrReadByte = (byte)((slaveAddress << 1) | 0x01);
        Log(I2CEventType.AddressRead, $"SLA+R (0x{slaveAddress:X2} << 1 | 1 = 0x{addrReadByte:X2})", new[] { addrReadByte });
        Log(I2CEventType.Ack, $"ACK received from Slave 0x{slaveAddress:X2}");

        byte[] data = slave.HandleRead(registerAddress, requestedLength);

        Log(I2CEventType.DataRead, $"Received {data.Length} bytes from Slave: [{string.Join(" ", data.Select(b => $"0x{b:X2}"))}]", data);
        Log(I2CEventType.Nack, "Host issues NACK on last byte (signals end of read transfer)");
        Log(I2CEventType.Stop, "STOP condition generated by Host");

        return data;
    }

    /// <summary>
    /// Generates an ASCII logic analyzer trace visualization of recent transactions.
    /// </summary>
    public string GenerateAsciiWaveform(int maxEntries = 12)
    {
        var entries = _traceLog.TakeLast(maxEntries).ToList();
        if (entries.Count == 0) return "No bus transactions recorded.";

        var sb = new StringBuilder();
        sb.AppendLine("+========================================================================================+");
        sb.AppendLine("| VIRTUAL I2C LOGIC ANALYZER / PROTOCOL BUS TRACE                                        |");
        sb.AppendLine("+========================================================================================+");

        foreach (var entry in entries)
        {
            string symbol = entry.EventType switch
            {
                I2CEventType.Start => "[S]  START       ",
                I2CEventType.RepeatedStart => "[Sr] REPEATED ST ",
                I2CEventType.AddressWrite => "[W]  ADDR+WRITE  ",
                I2CEventType.AddressRead => "[R]  ADDR+READ   ",
                I2CEventType.RegisterAddress => "[REG]SUB-ADDRESS ",
                I2CEventType.DataRead => "[DAT]SLAVE->HOST ",
                I2CEventType.DataWrite => "[DAT]HOST->SLAVE ",
                I2CEventType.Ack => "[ACK]ACK         ",
                I2CEventType.Nack => "[NAK]NACK        ",
                I2CEventType.Stop => "[P]  STOP        ",
                _ => "[?]  UNKNOWN     "
            };

            sb.AppendFormat("| {0} | {1,-65} |\n", symbol, entry.Description);
        }
        sb.AppendLine("+========================================================================================+");
        return sb.ToString();
    }
}
