using System.Text;
using HidI2cSimulation.Simulation;

namespace HidI2cSimulation.Hardware;

/// <summary>
/// =========================================================================================
///  I2C BUS SIMULATION WITH LOGIC ANALYZER / WIRE TRACER
/// =========================================================================================
///
///  The Inter-Integrated Circuit (I2C) bus uses 2 bi-directional open-drain lines:
///    - SCL (Serial Clock)
///    - SDA (Serial Data)
///
///  A typical HID-over-I2C Read transaction has this exact structure:
///
///  1. Host sends START condition (SDA pulled Low while SCL is High).
///  2. Host sends 7-bit Slave Address + Write bit (0).
///  3. Slave responds with ACK (A = 0).
///  4. Host transmits 16-bit Register Address (Sub-Address) in Little-Endian:
///     - Register Low Byte  (e.g., 0x01) -> Slave ACK
///     - Register High Byte (e.g., 0x00) -> Slave ACK
///  5. Host sends REPEATED START (Sr) without releasing the bus.
///  6. Host sends 7-bit Slave Address + Read bit (1).
///  7. Slave responds with ACK.
///  8. Slave streams Data bytes:
///     - Byte 0: Length LSB -> Host ACK
///     - Byte 1: Length MSB -> Host ACK
///     - Byte 2..N: Payload -> Host ACK (Host NACK on final byte)
///  9. Host sends STOP condition (SDA pulled High while SCL is High).
///
///  ASCII TIMING DIAGRAM:
///
///          +---+ +---+ +---+ +---+ +---+ +---+ +---+ +---+ +---+     +---+ +---+
///  SCL:  __| 1 |_| 2 |_| 3 |_| 4 |_| 5 |_| 6 |_| 7 |_| 8 |_| 9 | ... | 8 |_| 9 |__
///        ---             Slave Address (7-bit) + W     ACK         Data  NACK/P
///  SDA:  \___[ A6 ][ A5 ][ A4 ][ A3 ][ A2 ][ A1 ][ A0 ][ W ][ 0 ] ... [D0][ 1 ]---/
///        ^                                            ^              ^
///      START                                         ACK            STOP
///
/// =========================================================================================
/// </summary>

public interface II2CSlave
{
    byte I2CAddress { get; }
    byte[] HandleRead(ushort registerAddress, int requestedLength);
    bool HandleWrite(ushort registerAddress, byte[] data);
}

public enum I2CEventType
{
    Start,
    RepeatedStart,
    AddressWrite,
    AddressRead,
    RegisterAddress,
    DataRead,
    DataWrite,
    Ack,
    Nack,
    Stop
}

public record I2CTraceRecord(
    DateTime Timestamp,
    I2CEventType EventType,
    string Description,
    byte[]? RawBytes = null
);

public class I2CBus
{
    private readonly Dictionary<byte, II2CSlave> _slaves = new();
    private readonly List<I2CTraceRecord> _traceLog = new();
    private LogicAnalyzerCapture? _capture;
    private string? _pendingSemanticCategory;
    private string? _pendingSemanticSummary;

    public IReadOnlyList<I2CTraceRecord> TraceLog => _traceLog;
    public event Action<I2CTraceRecord>? OnTrace;
    public event Action<BusTransactionSummary>? OnTransactionCompleted;

    public void AttachLogicAnalyzer(LogicAnalyzerCapture? capture)
    {
        _capture = capture;
    }

    public void SetNextTransactionSemantic(string category, string summary)
    {
        _pendingSemanticCategory = category;
        _pendingSemanticSummary = summary;
    }

    public void RegisterSlave(II2CSlave slave)
    {
        _slaves[slave.I2CAddress] = slave;
    }

    public void ClearTrace()
    {
        _traceLog.Clear();
    }

    private void Log(I2CEventType type, string desc, byte[]? data = null)
    {
        var record = new I2CTraceRecord(DateTime.UtcNow, type, desc, data);
        _traceLog.Add(record);
        OnTrace?.Invoke(record);
    }

    private (string category, string summary) ConsumeSemantic(string defaultCategory, string defaultSummary)
    {
        string category = _pendingSemanticCategory ?? defaultCategory;
        string summary = _pendingSemanticSummary ?? defaultSummary;
        _pendingSemanticCategory = null;
        _pendingSemanticSummary = null;
        return (category, summary);
    }

    /// <summary>
    /// Performs an I2C Write transaction:
    /// [START] -> [Addr + W] -> [Reg LSB] -> [Reg MSB] -> [Data...] -> [STOP]
    /// </summary>
    public bool Write(byte slaveAddress, ushort registerAddress, byte[] data)
    {
        (string category, string summary) = ConsumeSemantic(
            "I2C Write",
            $"Write Reg 0x{registerAddress:X4} ({data.Length}B)");

        long txStartNs = 0;
        if (_capture != null)
        {
            _capture.EmitIdleGap();
            txStartNs = _capture.Timeline.CurrentTimeNs;
            _capture.EmitI2cStart();
        }

        Log(I2CEventType.Start, "START condition generated by Host");

        byte addrByte = (byte)((slaveAddress << 1) | 0x00);
        Log(I2CEventType.AddressWrite, $"SLA+W (0x{slaveAddress:X2} << 1 | 0 = 0x{addrByte:X2})", new[] { addrByte });

        if (!_slaves.TryGetValue(slaveAddress, out var slave))
        {
            _capture?.EmitI2cByte(addrByte, false, I2cFrameKind.AddressWrite, $"0x{slaveAddress:X2}+W", $"SLA+W 0x{addrByte:X2} (NACK)");
            _capture?.EmitI2cStop();

            Log(I2CEventType.Nack, $"NACK! No slave responded at address 0x{slaveAddress:X2}");
            Log(I2CEventType.Stop, "STOP condition generated");

            EmitTransactionSummary(txStartNs, isRead: false, slaveAddress, registerAddress, 0, acked: false, category, summary, "Slave did not ACK", data);
            return false;
        }

        _capture?.EmitI2cByte(addrByte, true, I2cFrameKind.AddressWrite, $"0x{slaveAddress:X2}+W", $"SLA+W: Slave 0x{slaveAddress:X2} Write (0x{addrByte:X2})");
        Log(I2CEventType.Ack, $"ACK received from Slave 0x{slaveAddress:X2}");

        byte regLsb = (byte)(registerAddress & 0xFF);
        byte regMsb = (byte)((registerAddress >> 8) & 0xFF);
        _capture?.EmitI2cByte(regLsb, true, I2cFrameKind.RegisterAddress, $"RegL 0x{regLsb:X2}", $"Register Sub-Address LSB (0x{registerAddress:X4})");
        _capture?.EmitI2cByte(regMsb, true, I2cFrameKind.RegisterAddress, $"RegH 0x{regMsb:X2}", $"Register Sub-Address MSB (0x{registerAddress:X4})");

        Log(I2CEventType.RegisterAddress, $"Register Sub-Address: 0x{registerAddress:X4} [LSB: 0x{regLsb:X2}, MSB: 0x{regMsb:X2}]", new[] { regLsb, regMsb });
        Log(I2CEventType.Ack, "ACK for Register Address bytes");

        if (data.Length > 0)
        {
            if (_capture != null)
            {
                for (int i = 0; i < data.Length; i++)
                {
                    _capture.EmitI2cByte(data[i], true, I2cFrameKind.DataWrite, $"W 0x{data[i]:X2}", $"Data[{i}] Host -> Slave: 0x{data[i]:X2}");
                }
            }
            Log(I2CEventType.DataWrite, $"Writing {data.Length} data bytes: [{string.Join(" ", data.Select(b => $"0x{b:X2}"))}]", data);
            Log(I2CEventType.Ack, $"ACK for Data Payload ({data.Length} bytes)");
        }

        bool result = slave.HandleWrite(registerAddress, data);
        _capture?.EmitI2cStop();
        Log(I2CEventType.Stop, "STOP condition generated by Host");

        EmitTransactionSummary(
            txStartNs,
            isRead: false,
            slaveAddress,
            registerAddress,
            data.Length,
            acked: true,
            category,
            summary,
            $"Reg 0x{registerAddress:X4} <- [{string.Join(" ", data.Select(b => $"{b:X2}"))}]",
            data);

        return result;
    }

    /// <summary>
    /// Performs an I2C Read transaction using Repeated Start:
    /// [START] -> [Addr + W] -> [Reg LSB] -> [Reg MSB] -> [REPEATED START] -> [Addr + R] -> [Read Data...] -> [STOP]
    /// </summary>
    public byte[] Read(byte slaveAddress, ushort registerAddress, int requestedLength)
    {
        (string category, string summary) = ConsumeSemantic(
            "I2C Read",
            $"Read Reg 0x{registerAddress:X4} ({requestedLength}B)");

        long txStartNs = 0;
        if (_capture != null)
        {
            _capture.EmitIdleGap();
            txStartNs = _capture.Timeline.CurrentTimeNs;
            _capture.EmitI2cStart();
        }

        Log(I2CEventType.Start, "START condition generated by Host");

        byte addrWriteByte = (byte)((slaveAddress << 1) | 0x00);
        Log(I2CEventType.AddressWrite, $"SLA+W (0x{slaveAddress:X2} << 1 | 0 = 0x{addrWriteByte:X2})", new[] { addrWriteByte });

        if (!_slaves.TryGetValue(slaveAddress, out var slave))
        {
            _capture?.EmitI2cByte(addrWriteByte, false, I2cFrameKind.AddressWrite, $"0x{slaveAddress:X2}+W", $"SLA+W 0x{addrWriteByte:X2} (NACK)");
            _capture?.EmitI2cStop();

            Log(I2CEventType.Nack, $"NACK! No slave responded at address 0x{slaveAddress:X2}");
            Log(I2CEventType.Stop, "STOP condition generated");

            EmitTransactionSummary(txStartNs, isRead: true, slaveAddress, registerAddress, 0, acked: false, category, summary, "Slave did not ACK", Array.Empty<byte>());
            return Array.Empty<byte>();
        }

        _capture?.EmitI2cByte(addrWriteByte, true, I2cFrameKind.AddressWrite, $"0x{slaveAddress:X2}+W", $"SLA+W: Slave 0x{slaveAddress:X2} Write (0x{addrWriteByte:X2})");
        Log(I2CEventType.Ack, $"ACK received from Slave 0x{slaveAddress:X2}");

        byte regLsb = (byte)(registerAddress & 0xFF);
        byte regMsb = (byte)((registerAddress >> 8) & 0xFF);
        _capture?.EmitI2cByte(regLsb, true, I2cFrameKind.RegisterAddress, $"RegL 0x{regLsb:X2}", $"Register Sub-Address LSB (0x{registerAddress:X4})");
        _capture?.EmitI2cByte(regMsb, true, I2cFrameKind.RegisterAddress, $"RegH 0x{regMsb:X2}", $"Register Sub-Address MSB (0x{registerAddress:X4})");

        Log(I2CEventType.RegisterAddress, $"Register Sub-Address: 0x{registerAddress:X4} [LSB: 0x{regLsb:X2}, MSB: 0x{regMsb:X2}]", new[] { regLsb, regMsb });
        Log(I2CEventType.Ack, "ACK for Register Address bytes");

        // Repeated Start to switch from Write (sub-addressing) to Read mode
        _capture?.EmitI2cRepeatedStart();
        Log(I2CEventType.RepeatedStart, "REPEATED START (Sr) condition generated by Host");

        byte addrReadByte = (byte)((slaveAddress << 1) | 0x01);
        _capture?.EmitI2cByte(addrReadByte, true, I2cFrameKind.AddressRead, $"0x{slaveAddress:X2}+R", $"SLA+R: Slave 0x{slaveAddress:X2} Read (0x{addrReadByte:X2})");
        Log(I2CEventType.AddressRead, $"SLA+R (0x{slaveAddress:X2} << 1 | 1 = 0x{addrReadByte:X2})", new[] { addrReadByte });
        Log(I2CEventType.Ack, $"ACK received from Slave 0x{slaveAddress:X2}");

        // Hold any INT# pin release until after all DataRead bytes are clocked on the LA waveform
        var deferredPinUpdates = new List<(LogicChannelId Channel, byte Level)>();
        byte[] data = ReadSlaveWithDeferredCapture(slave, registerAddress, requestedLength, deferredPinUpdates);

        if (_capture != null)
        {
            for (int i = 0; i < data.Length; i++)
            {
                bool hostAck = i < data.Length - 1; // Host NACKs the final byte before STOP
                _capture.EmitI2cByte(
                    data[i],
                    hostAck,
                    I2cFrameKind.DataRead,
                    $"R 0x{data[i]:X2}",
                    $"Data[{i}] Slave -> Host: 0x{data[i]:X2} ({(hostAck ? "Host ACK" : "Host NACK")})");
            }

            foreach (var (ch, lvl) in deferredPinUpdates)
            {
                _capture.RecordPinState(ch, _capture.Timeline.CurrentTimeNs, lvl);
            }
        }

        Log(I2CEventType.DataRead, $"Received {data.Length} bytes from Slave: [{string.Join(" ", data.Select(b => $"0x{b:X2}"))}]", data);
        Log(I2CEventType.Nack, "Host issues NACK on last byte (signals end of read transfer)");

        _capture?.EmitI2cStop();
        Log(I2CEventType.Stop, "STOP condition generated by Host");

        EmitTransactionSummary(
            txStartNs,
            isRead: true,
            slaveAddress,
            registerAddress,
            data.Length,
            acked: true,
            category,
            summary,
            $"Reg 0x{registerAddress:X4} -> {data.Length} bytes",
            data);

        return data;
    }

    private byte[] ReadSlaveWithDeferredCapture(
        II2CSlave slave,
        ushort registerAddress,
        int requestedLength,
        List<(LogicChannelId Channel, byte Level)> deferredPinUpdates)
    {
        if (_capture == null || slave is not Device.HidI2cDevice dev)
            return slave.HandleRead(registerAddress, requestedLength);

        // Temporarily hold INT# release edge until end of I2C data phase
        byte beforeInt = (byte)dev.InterruptPin.CurrentState;
        dev.InterruptPin.SetLogicAnalyzerTraceSuspended(true);
        try
        {
            byte[] result = slave.HandleRead(registerAddress, requestedLength);
            byte afterInt = (byte)dev.InterruptPin.CurrentState;
            if (afterInt != beforeInt)
                deferredPinUpdates.Add((LogicChannelId.Int, afterInt));
            return result;
        }
        finally
        {
            dev.InterruptPin.SetLogicAnalyzerTraceSuspended(false);
        }
    }

    private void EmitTransactionSummary(
        long txStartNs,
        bool isRead,
        byte slaveAddress,
        ushort registerAddress,
        int byteCount,
        bool acked,
        string category,
        string summary,
        string detail,
        byte[] data)
    {
        if (_capture != null)
        {
            long txEndNs = _capture.Timeline.CurrentTimeNs;
            int id = _capture.AddTransaction(txStartNs, txEndNs, isRead, slaveAddress, registerAddress, byteCount, acked, category, summary, detail, data);
            var tx = _capture.Transactions.FirstOrDefault(t => t.Id == id);
            if (tx != null)
                OnTransactionCompleted?.Invoke(tx);
        }
        else
        {
            var tx = new BusTransactionSummary(0, 0, 0, isRead, slaveAddress, registerAddress, byteCount, acked, summary, data);
            OnTransactionCompleted?.Invoke(tx);
        }
    }

    /// <summary>
    /// Generates an ASCII logic analyzer trace visualization of recent transactions.
    /// </summary>
    public string GenerateAsciiWaveform(int maxEntries = 12)
    {
        var entries = _traceLog.TakeLast(maxEntries).ToList();
        if (entries.Count == 0) return "No bus transactions recorded.";

        var sb = new StringBuilder();
        sb.AppendLine("+========================================================================================+");
        sb.AppendLine("| VIRTUAL I2C LOGIC ANALYZER / PROTOCOL BUS TRACE                                        |");
        sb.AppendLine("+========================================================================================+");

        foreach (var entry in entries)
        {
            string symbol = entry.EventType switch
            {
                I2CEventType.Start => "[S]  START       ",
                I2CEventType.RepeatedStart => "[Sr] REPEATED ST ",
                I2CEventType.AddressWrite => "[W]  ADDR+WRITE  ",
                I2CEventType.AddressRead => "[R]  ADDR+READ   ",
                I2CEventType.RegisterAddress => "[REG]SUB-ADDRESS ",
                I2CEventType.DataRead => "[DAT]SLAVE->HOST ",
                I2CEventType.DataWrite => "[DAT]HOST->SLAVE ",
                I2CEventType.Ack => "[ACK]ACK         ",
                I2CEventType.Nack => "[NAK]NACK        ",
                I2CEventType.Stop => "[P]  STOP        ",
                _ => "[?]  UNKNOWN     "
            };

            sb.AppendFormat("| {0} | {1,-65} |\n", symbol, entry.Description);
        }
        sb.AppendLine("+========================================================================================+");
        return sb.ToString();
    }
}
